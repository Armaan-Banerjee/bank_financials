#!/usr/bin/env python3
"""Generate scripts/overview_spec.py — the Overview derivation spec.

Standing objective (b): the Overview's money blocks are DERIVED from the
detail sheets rather than hand-copied alongside them, so a correction applied
to a detail sheet can no longer be missed on the Overview.

Most Overview rows resolve by their own label. This tool discovers the rest,
ONCE, by running every build script and value-matching each unresolved row
against its detail sheet:

  - exactly one detail row carries the same values  -> an ALIAS (the Overview
    simply renames the row, e.g. "Customer deposits" for "Deposits from
    customers").
  - no single row matches                           -> reported for a human,
    because these are usually AGGREGATES the detail sheet never totals (e.g.
    "Total operating expense" summed from its components), and a sum cannot
    be inferred safely.
  - several rows match                              -> reported for a human,
    because picking one arbitrarily would bake in a coin-flip.

Discovery is a one-time act, not a build-time one: the match is made against
the very literals being replaced, so inferring it on every build would
silently fall back to the stale value the moment a detail sheet was corrected.

    python3 scripts/derive_overview_spec.py            # report only
    python3 scripts/derive_overview_spec.py --write    # write the spec module

Re-run it after adding a bank; it reports anything new that needs a decision.
"""

import argparse
import glob
import os
import pprint
import runpy
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import bank_workbook as BW  # noqa: E402

SPEC_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         "overview_spec.py")

HEADER = """\"\"\"Overview derivation spec for standing objective (b).

DISCOVERED is generated by derive_overview_spec.py - do not hand-edit it;
re-run the generator. HAND is written by a person and the generator never
touches it: an aggregate cannot be discovered safely, so each one below was
read off the bank\'s own detail sheet.

  (bank_name, detail sheet, normalised Overview label) -> either
      "detail row label"          the Overview simply renames the row
      ("row a", "row b", ...)     the Overview totals rows the sheet does not
      (("row a", -1), ("row b", 1))   signed terms, for a residual
      OVERVIEW_KEEP_LITERAL       not derivable; see wayfinder/gaps/map.md
\"\"\"

from bank_workbook import OVERVIEW_KEEP_LITERAL  # noqa: F401

"""


def fmt(mapping, name):
    lines = [f"{name} = {{"]
    for (bank, sheet, label) in sorted(mapping):
        value = mapping[(bank, sheet, label)]
        if value == "OVERVIEW_KEEP_LITERAL":
            rhs = "OVERVIEW_KEEP_LITERAL"
        else:
            rhs = repr(value)
        lines.append(f"    ({bank!r},\n     {sheet!r},\n     {label!r}):\n        {rhs},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def discover():
    """Run every build script with derivation in discovery mode."""
    BW._unresolved.clear()
    saved = BW.BankWorkbook.save
    BW.BankWorkbook.save = lambda self, path: path  # don't touch banks/
    captured = []
    try:
        for script in sorted(glob.glob(os.path.join(
                os.path.dirname(os.path.abspath(__file__)), "build_*.py"))):
            before = len(BW._unresolved)
            argv = sys.argv
            sys.argv = [script]
            try:
                runpy.run_path(script, run_name="__main__")
            except Exception as exc:  # a build that cannot run tells us so
                print(f"!! {os.path.basename(script)} did not run: "
                      f"{type(exc).__name__}: {exc}", file=sys.stderr)
            finally:
                sys.argv = argv
            captured.extend(BW._unresolved[before:])
    finally:
        BW.BankWorkbook.save = saved
    return captured


def resolve(unresolved, printed_years=None):
    """Map each unresolved Overview row onto the detail row(s) it came from.

    A single matching row is the common case. But some Overview rows span a
    PRESENTATION BREAK: the bank restated its statement partway through the
    window, so the same quantity appears under two differently-named rows
    covering disjoint year ranges, and no single row covers the Overview row.
    Those resolve to a UNION - summing rows whose years do not overlap is a
    merge, not an addition.

    A candidate only counts if it covers EVERY year the Overview prints.
    Settling for a row that matches two years is how a mapping gets chosen
    that silently blanks the rest.
    """
    aliases, ambiguous, orphans = {}, [], []
    for bank, sheet, block, label, values, table, years in unresolved:
        want = {y: v for y, v in values.items()
                if isinstance(v, (int, float))
                and (years is None or y in years)}
        if not want:
            continue
        rows = {k: {y: v for y, v in r.items() if isinstance(v, (int, float))}
                for k, r in table.items()}

        def agrees(key, year):
            return year in rows[key] and abs(rows[key][year] - want[year]) < 0.01

        full = [k for k in rows if all(agrees(k, y) for y in want)]
        if not full:
            # the detail sheet may simply not carry every year the Overview
            # shows; a row that agrees wherever it HAS a year, and covers
            # most of them, is still the right source (the rest stay literal
            # and are recorded - see _keep_what_detail_lacks)
            best = 0
            for k in rows:
                hit = [y for y in want if y in rows[k]]
                if hit and all(agrees(k, y) for y in hit) and len(hit) > best:
                    best = len(hit)
            if best >= max(2, len(want) - 3):
                full = [k for k in rows
                        if len([y for y in want if y in rows[k]]) == best
                        and all(agrees(k, y) for y in want if y in rows[k])]
        entry = (bank, sheet, BW._norm_label(label))
        if len(full) == 1:
            aliases[entry] = full[0]
            continue
        if len(full) > 1:
            ambiguous.append((entry, full))
            continue
        # no single row covers every year - try a union of rows that each
        # cover part of the range and agree wherever they apply
        parts, covered = [], set()
        for key in sorted(rows, key=lambda k: -len(set(rows[k]) & set(want))):
            gain = {y for y in want if y not in covered and agrees(key, y)}
            if gain:
                parts.append(key)
                covered |= gain
            if covered == set(want):
                break
        if covered == set(want) and 1 < len(parts) <= 3:
            # a true union: no year may be supplied by two parts
            overlap = any(
                sum(1 for k in parts if y in rows[k]) > 1 for y in want
            )
            if not overlap:
                aliases[entry] = tuple(parts)
                continue
        orphans.append((entry, sorted(want.items())[:3]))
    return aliases, ambiguous, orphans


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()

    unresolved = discover()
    aliases, ambiguous, orphans = resolve(unresolved)

    print(f"unresolved Overview rows: {len(unresolved)}")
    print(f"  resolved to one detail row (alias): {len(aliases)}")
    print(f"  ambiguous, need a human decision  : {len(ambiguous)}")
    print(f"  no match - likely AGGREGATES      : {len(orphans)}")
    if ambiguous:
        print("\nAMBIGUOUS:")
        for (bank, sheet, key), cands in ambiguous:
            print(f"  {bank} [{sheet}] {key} -> {cands}")
    if orphans:
        print("\nNO MATCH (write an aggregate spec by hand):")
        for (bank, sheet, key), sample in orphans:
            print(f"  {bank} [{sheet}] {key}  values={sample}")

    if args.write:
        hand = {}
        if os.path.exists(SPEC_PATH):
            ns = runpy.run_path(SPEC_PATH)
            hand = dict(ns.get("HAND", {}))
        with open(SPEC_PATH, "w") as fh:
            fh.write(HEADER)
            fh.write("\n# -- discovered by value-matching; regenerated ------------------------------\n")
            fh.write(fmt(aliases, "DISCOVERED"))
            fh.write("\n# -- written by hand; the generator never rewrites this ---------------------\n")
            fh.write(fmt(hand, "HAND"))
            fh.write("\nOVERVIEW_SPEC = dict(DISCOVERED)\nOVERVIEW_SPEC.update(HAND)\n")
        print(f"\nwrote {len(aliases)} discovered + {len(hand)} hand entries "
              f"to {SPEC_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
